//! `orbital-mock-export <out-dir> [<previews-dir>]`: writes `orbital.css`, `tokens.css`,
//! and `fonts/` for static HTML mocks. With a second directory, also writes each
//! preview's rendered HTML as `<slug>.html`, the reference markup for mock elements.
//! See the crate docs in `lib.rs`.

use std::path::{Path, PathBuf};
use std::process::{Command, ExitCode};

use leptos::prelude::*;
use leptos_meta::provide_meta_context;
use orbital_mock_export::{declarations_of, tokens_css, StyleCollector};
use orbital_preview_app::preview::collect_preview_registrations;
use orbital_style::StyleRegistry;
use orbital_theme::{
    font_faces_css_with_asset_prefix, theme_scoped_vars_css, OrbitalThemeProvider, Theme,
};

/// Hidden flag: render one preview (by index) to stdout. The parent process runs
/// each preview this way because a few call browser-only APIs during SSR, which
/// aborts the process rather than unwinding.
const RENDER_ONE: &str = "--render-one";

fn main() -> ExitCode {
    if std::env::args().nth(1).as_deref() == Some(RENDER_ONE) {
        return render_one(std::env::args().nth(2));
    }
    let mut args = std::env::args_os().skip(1).map(PathBuf::from);
    let Some(out_dir) = args.next() else {
        eprintln!("usage: orbital-mock-export <out-dir> [<previews-dir>]");
        return ExitCode::from(2);
    };
    let previews_dir = args.next();
    match run(&out_dir, previews_dir.as_deref()) {
        Ok(()) => ExitCode::SUCCESS,
        Err(err) => {
            eprintln!("orbital-mock-export: {err}");
            ExitCode::FAILURE
        }
    }
}

fn run(out_dir: &Path, previews_dir: Option<&Path>) -> Result<(), String> {
    let workspace = Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .ok_or("crate has no parent directory")?;
    let rev = git_rev(workspace);
    let header = format!(
        "/* Generated by orbital-mock-export from Orbital {rev}. Do not edit; re-run the export. */\n"
    );

    let mut collector = StyleCollector::default();
    let registrations = collect_preview_registrations();
    if let Some(dir) = previews_dir {
        std::fs::create_dir_all(dir).map_err(|err| format!("create {}: {err}", dir.display()))?;
    }
    let exe = std::env::current_exe().map_err(|err| format!("current exe: {err}"))?;
    let mut skipped = Vec::new();
    for (index, registration) in registrations.iter().enumerate() {
        let output = Command::new(&exe)
            .args([RENDER_ONE, &index.to_string()])
            .stderr(std::process::Stdio::null())
            .output()
            .map_err(|err| format!("spawn renderer: {err}"))?;
        if !output.status.success() {
            skipped.push(registration.slug);
            continue;
        }
        let html = String::from_utf8_lossy(&output.stdout);
        collector.add_html(&html);
        if let Some(dir) = previews_dir {
            let name = match registration.slug {
                "" => "index".to_string(),
                slug => slug.replace('/', "__"),
            };
            write(&dir.join(format!("{name}.html")), &html)?;
        }
    }
    if collector.is_empty() {
        return Err("no component styles collected; did the previews render?".into());
    }

    std::fs::create_dir_all(out_dir)
        .map_err(|err| format!("create {}: {err}", out_dir.display()))?;
    write(&out_dir.join("orbital.css"), &collector.to_css(&header))?;

    let light = theme_scoped_vars_css("0", &Theme::light());
    let dark = theme_scoped_vars_css("0", &Theme::dark());
    let tokens = tokens_css(
        &header,
        &font_faces_css_with_asset_prefix("fonts"),
        declarations_of(&light),
        declarations_of(&dark),
    );
    write(&out_dir.join("tokens.css"), &tokens)?;

    copy_dir(&workspace.join("public/fonts"), &out_dir.join("fonts"))?;
    write(&out_dir.join("ORBITAL_REV"), &format!("{rev}\n"))?;

    if !skipped.is_empty() {
        eprintln!(
            "orbital-mock-export: {} previews failed to render on the server and were skipped: {}",
            skipped.len(),
            skipped.join(", ")
        );
    }
    println!(
        "orbital-mock-export: {} previews, {} style blocks, Orbital {rev} -> {}",
        registrations.len() - skipped.len(),
        collector.len(),
        out_dir.display()
    );
    Ok(())
}

fn render_one(index: Option<String>) -> ExitCode {
    let Some(index) = index.and_then(|i| i.parse::<usize>().ok()) else {
        return ExitCode::from(2);
    };
    let Some(registration) = collect_preview_registrations().get(index).copied() else {
        return ExitCode::from(2);
    };
    // Some components spawn local tasks during SSR (see orbital-preview-server).
    if any_spawner::Executor::init_futures_executor().is_err() {
        return ExitCode::FAILURE;
    }
    print!("{}", render_registration(registration.render));
    ExitCode::SUCCESS
}

/// Renders one preview inside a theme provider and style registry and returns the HTML,
/// with injected styles placed in `<head>`.
fn render_registration(render: fn() -> AnyView) -> String {
    let owner = Owner::new();
    owner.with(|| {
        provide_meta_context();
        view! {
            <StyleRegistry>
                <html>
                    <head><meta name="orbital-style"/></head>
                    <body>
                        <OrbitalThemeProvider theme=RwSignal::new(Theme::light())>
                            {render()}
                        </OrbitalThemeProvider>
                    </body>
                </html>
            </StyleRegistry>
        }
        .to_html()
    })
}

fn git_rev(dir: &Path) -> String {
    Command::new("git")
        .args(["describe", "--always", "--dirty", "--abbrev=12"])
        .current_dir(dir)
        .output()
        .ok()
        .filter(|out| out.status.success())
        .and_then(|out| String::from_utf8(out.stdout).ok())
        .map(|rev| rev.trim().to_string())
        .unwrap_or_else(|| "unknown".to_string())
}

fn write(path: &Path, contents: &str) -> Result<(), String> {
    std::fs::write(path, contents).map_err(|err| format!("write {}: {err}", path.display()))
}

fn copy_dir(from: &Path, to: &Path) -> Result<(), String> {
    std::fs::create_dir_all(to).map_err(|err| format!("create {}: {err}", to.display()))?;
    let entries =
        std::fs::read_dir(from).map_err(|err| format!("read {}: {err}", from.display()))?;
    for entry in entries {
        let entry = entry.map_err(|err| format!("read {}: {err}", from.display()))?;
        let target = to.join(entry.file_name());
        if entry.path().is_dir() {
            copy_dir(&entry.path(), &target)?;
        } else {
            std::fs::copy(entry.path(), &target)
                .map_err(|err| format!("copy {}: {err}", entry.path().display()))?;
        }
    }
    Ok(())
}
