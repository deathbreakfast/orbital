/// One emoji the picker can offer.
///
/// `name` is a shortcode-style id (`party_popper`); the picker shows it with spaces as the
/// button's accessible name and matches searches against it and `keywords`.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Emoji {
    /// The emoji itself, as it should be inserted (may include a variation selector).
    pub glyph: &'static str,
    /// Shortcode-style name, lowercase with underscores.
    pub name: &'static str,
    /// Extra search terms.
    pub keywords: &'static [&'static str],
}

impl Emoji {
    /// `name` with underscores turned into spaces, used as the accessible name.
    pub fn label(&self) -> String {
        self.name.replace('_', " ")
    }
}

macro_rules! emoji {
    ($glyph:literal, $name:literal $(, $kw:literal)* $(,)?) => {
        Emoji { glyph: $glyph, name: $name, keywords: &[$($kw),*] }
    };
}

